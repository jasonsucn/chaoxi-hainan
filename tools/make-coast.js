/* 把海南省边界里最大的那块（主岛）抽出来，normalize 成 1000x862 的图版坐标。
   数据源：阿里 DataV GeoAtlas 460000.json，仅取主岛轮廓。
   运行：node tools/make-coast.js  →  js/coast.js */
const fs = require('fs');
const path = require('path');

(async () => {
  const url = 'https://geo.datav.aliyun.com/areas_v3/bound/460000.json';
  const res = await fetch(url, { signal: AbortSignal.timeout(25000) });
  const json = await res.json();

  const polys = json.features[0].geometry.coordinates;
  let best = null, bestArea = 0;
  for (const poly of polys) {
    const ring = poly[0];
    let a = 0;
    for (let i = 0; i < ring.length - 1; i++) {
      a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
    }
    a = Math.abs(a / 2);
    if (a > bestArea) { bestArea = a; best = ring; }
  }

  const lons = best.map(p => p[0]);
  const lats = best.map(p => p[1]);
  const minLon = Math.min(...lons), maxLon = Math.max(...lons);
  const minLat = Math.min(...lats), maxLat = Math.max(...lats);
  const midLat = (minLat + maxLat) / 2;
  const cos = Math.cos(midLat * Math.PI / 180);

  const W = 1000;
  const H = Math.round(W * (maxLat - minLat) / ((maxLon - minLon) * cos));

  const nx = lon => (lon - minLon) / (maxLon - minLon);
  const ny = lat => (maxLat - lat) / (maxLat - minLat);

  const pts = best.map(p => [
    +(nx(p[0]) * W).toFixed(1),
    +(ny(p[1]) * H).toFixed(1)
  ]);

  // 去掉闭合重复点
  if (pts.length > 2) {
    const a = pts[0], b = pts[pts.length - 1];
    if (Math.abs(a[0] - b[0]) < 0.01 && Math.abs(a[1] - b[1]) < 0.01) pts.pop();
  }

  const d = 'M' + pts.map(p => p[0] + ' ' + p[1]).join('L') + 'Z';

  const cityDefs = [
    ['海口', 110.33119, 20.031971],
    ['文昌', 110.72, 19.61],
    ['五指山', 109.516, 18.817],
    ['三亚', 109.511, 18.252]
  ];
  const cities = cityDefs.map(([name, lon, lat]) => ({
    name,
    x: +(nx(lon) * W).toFixed(1),
    y: +(ny(lat) * H).toFixed(1)
  }));

  const out = `/* generated by tools/make-coast.js — 海南岛主岛轮廓，非精确测绘，仅作视觉图版 */
window.COAST = {
  w: ${W},
  h: ${H},
  path: ${JSON.stringify(d)},
  cities: ${JSON.stringify(cities)}
};
`;

  fs.writeFileSync(path.join(__dirname, '..', 'js', 'coast.js'), out);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <rect width="${W}" height="${H}" fill="#f2ecdf"/>
  <path d="${d}" fill="#111310" fill-opacity="0.04" stroke="#111310" stroke-opacity="0.55" stroke-width="2"/>
  ${cities.map(c => `<circle cx="${c.x}" cy="${c.y}" r="4" fill="#d8503a"/><text x="${c.x + 10}" y="${c.y + 6}" font-family="sans-serif" font-size="16" fill="#111310">${c.name}</text>`).join('\n  ')}
</svg>`;
  fs.writeFileSync(path.join(__dirname, '..', 'docs', 'coast-preview.svg'), svg);

  console.log('W,H', W, H, 'points', pts.length, 'area', bestArea.toFixed(4));
  console.log('bbox', minLon.toFixed(3), maxLon.toFixed(3), minLat.toFixed(3), maxLat.toFixed(3));
  console.log('cities', JSON.stringify(cities));
})();
